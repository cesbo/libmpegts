fn psi_check_crc32(data: &[u8]) -> bool {
    let crc32_calculated = crc32b(&data[.. data.len() - 4]);
    let crc32_expected = u32::from_be_bytes([
        data[data.len() - 4],
        data[data.len() - 3],
        data[data.len() - 2],
        data[data.len() - 1],
    ]);
    crc32_calculated == crc32_expected
}

